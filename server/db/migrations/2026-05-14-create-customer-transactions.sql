CREATE TABLE IF NOT EXISTS customer_transactions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  prevaluation_id BIGINT UNSIGNED DEFAULT NULL,
  booking_id BIGINT UNSIGNED DEFAULT NULL,
  transaction_type ENUM('appraisal_fee','token_transfer','token_mint','token_sale','token_buy','other') NOT NULL DEFAULT 'other',
  direction ENUM('debit','credit') NOT NULL DEFAULT 'debit',
  status ENUM('pending','processing','paid','failed','cancelled','refunded') NOT NULL DEFAULT 'pending',
  amount DECIMAL(18,2) NOT NULL DEFAULT 0.00,
  currency VARCHAR(16) NOT NULL DEFAULT 'AED',
  payment_provider VARCHAR(64) DEFAULT NULL,
  provider_reference VARCHAR(191) DEFAULT NULL,
  provider_session_id VARCHAR(191) DEFAULT NULL,
  provider_payment_intent_id VARCHAR(191) DEFAULT NULL,
  metadata_json JSON DEFAULT NULL,
  source_channel ENUM('web','mobile','api','system') NOT NULL DEFAULT 'web',
  occurred_at DATETIME DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_customer_tx_user_created (user_id, created_at),
  KEY idx_customer_tx_type_status (transaction_type, status),
  KEY idx_customer_tx_prevaluation (prevaluation_id),
  KEY idx_customer_tx_booking (booking_id),
  KEY idx_customer_tx_provider (payment_provider, provider_reference),
  UNIQUE KEY uk_customer_tx_provider_ref (payment_provider, provider_reference),
  CONSTRAINT fk_customer_tx_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_customer_tx_prevaluation FOREIGN KEY (prevaluation_id) REFERENCES ai_prevaluations(id) ON DELETE SET NULL,
  CONSTRAINT fk_customer_tx_booking FOREIGN KEY (booking_id) REFERENCES appraiser_bookings(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
